using System;
using System.Diagnostics;
using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;
using Debug = UnityEngine.Debug;

namespace SolarMajesty.EditorTools
{
    /// <summary>
    /// Release identity for a build: the version string, the app icons, and the
    /// StreamingAssets/build-info.json stamp the game can show.
    ///
    /// Version source, first hit wins: <c>-smVersion</c> on the command line, the SM_VERSION
    /// environment variable, game-ci's <c>-buildVersion</c>, a <c>vX.Y.Z</c> tag (GITHUB_REF or
    /// <c>git describe</c>), else <c>0.0.0-dev+&lt;shortsha&gt;</c>. See <see cref="BuildVersion"/>.
    /// </summary>
    public static class ReleaseStamp
    {
        public const string IconFolder = "Assets/Art/Icons";
        public const string IconPrefix = "SM_AppIcon_";

        /// <summary>Sizes generated by Tools/release/icons/make_app_icons.py.</summary>
        private static readonly int[] IconSizes = { 1024, 512, 256, 128, 64, 48, 32, 16 };

        /// <summary>PlayerSettings values a build overrides, so a local build leaves the project clean.</summary>
        public struct Snapshot
        {
            public string BundleVersion;
            public string MacBuildNumber;

            public void Restore()
            {
                if (BundleVersion != null) PlayerSettings.bundleVersion = BundleVersion;
                if (MacBuildNumber != null) PlayerSettings.macOS.buildNumber = MacBuildNumber;
            }
        }

        public static string ResolveVersion()
        {
            string requested = Arg("-smVersion")
                               ?? Env("SM_VERSION")
                               ?? Arg("-buildVersion");
            string tagOrRef = Env("GITHUB_REF") ?? Git("describe --tags --exact-match HEAD");
            return BuildVersion.Resolve(requested, tagOrRef, ResolveCommit());
        }

        public static string ResolveCommit()
        {
            return Arg("-smCommit") ?? Env("SM_COMMIT") ?? Env("GITHUB_SHA") ?? Git("rev-parse HEAD") ?? "";
        }

        /// <summary>
        /// Sets the version on the player. Windows has no separate field: the player takes
        /// bundleVersion. macOS CFBundleVersion must be numeric, so it gets the X.Y.Z core.
        /// </summary>
        public static Snapshot ApplyVersion(string version)
        {
            var snapshot = new Snapshot
            {
                BundleVersion = PlayerSettings.bundleVersion,
                MacBuildNumber = PlayerSettings.macOS.buildNumber
            };
            PlayerSettings.bundleVersion = version;
            PlayerSettings.macOS.buildNumber = BuildVersion.NumericCore(version);
            Debug.Log($"[Build] Version {version} (macOS build {PlayerSettings.macOS.buildNumber})");
            return snapshot;
        }

        /// <summary>
        /// Assigns Assets/Art/Icons as the default and Standalone icons. Missing files are skipped
        /// (the nearest larger size stands in); with no icons at all the project keeps its own.
        /// </summary>
        [MenuItem("Solar Majesty/Build/Apply App Icons", priority = 203)]
        public static bool ApplyIcons()
        {
            Texture2D master = LoadIcon(IconSizes[0]);
            if (master == null)
            {
                Debug.LogWarning($"[Build] No app icons under {IconFolder}; keeping the project's icon settings.");
                return false;
            }

            // Default icon: every platform without an override falls back to it.
            PlayerSettings.SetIcons(NamedBuildTarget.Unknown, new[] { master }, IconKind.Any);

            int[] sizes = PlayerSettings.GetIconSizes(NamedBuildTarget.Standalone, IconKind.Any);
            if (sizes == null || sizes.Length == 0) sizes = IconSizes;

            var icons = new Texture2D[sizes.Length];
            for (int i = 0; i < sizes.Length; i++)
                icons[i] = LoadIconAtLeast(sizes[i]) ?? master;
            PlayerSettings.SetIcons(NamedBuildTarget.Standalone, icons, IconKind.Any);

            Debug.Log($"[Build] App icons applied ({sizes.Length} Standalone sizes from {IconFolder}).");
            return true;
        }

        /// <summary>Writes build-info.json into a finished player. Never fails the build.</summary>
        public static void WriteBuildInfo(BuildTarget target, string outputPath)
        {
            try
            {
                bool mac = target == BuildTarget.StandaloneOSX;
                bool standalone = mac
                                  || target == BuildTarget.StandaloneWindows64
                                  || target == BuildTarget.StandaloneWindows
                                  || target == BuildTarget.StandaloneLinux64;
                if (!standalone || string.IsNullOrEmpty(outputPath)) return;

                string player = outputPath;
                if (mac && !player.EndsWith(".app", StringComparison.OrdinalIgnoreCase) && Directory.Exists(player + ".app"))
                    player += ".app";

                string dir = BuildVersion.StreamingAssetsDir(player, mac);
                Directory.CreateDirectory(dir);
                string json = BuildVersion.ToJson(PlayerSettings.bundleVersion, ResolveCommit(), target.ToString(), DateTime.UtcNow);
                string file = Path.Combine(dir, BuildVersion.FileName);
                File.WriteAllText(file, json);
                Debug.Log($"[Build] Stamped {file}");
            }
            catch (Exception e)
            {
                Debug.LogWarning($"[Build] Could not write {BuildVersion.FileName}: {e.Message}");
            }
        }

        private static Texture2D LoadIcon(int size)
        {
            return AssetDatabase.LoadAssetAtPath<Texture2D>($"{IconFolder}/{IconPrefix}{size}.png");
        }

        private static Texture2D LoadIconAtLeast(int size)
        {
            for (int i = IconSizes.Length - 1; i >= 0; i--)
            {
                if (IconSizes[i] < size) continue;
                Texture2D tex = LoadIcon(IconSizes[i]);
                if (tex != null) return tex;
            }
            return null;
        }

        internal static string Arg(string flag)
        {
            string[] args = Environment.GetCommandLineArgs();
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (args[i] == flag && !string.IsNullOrWhiteSpace(args[i + 1]) && !args[i + 1].StartsWith("-"))
                    return args[i + 1];
            }
            return null;
        }

        private static string Env(string name)
        {
            string v = Environment.GetEnvironmentVariable(name);
            return string.IsNullOrWhiteSpace(v) ? null : v.Trim();
        }

        /// <summary>One-line git output from the project root, or null (no git, not a repo, timeout).</summary>
        private static string Git(string arguments)
        {
            try
            {
                var info = new ProcessStartInfo("git", arguments)
                {
                    WorkingDirectory = Path.GetFullPath(Path.Combine(Application.dataPath, "..")),
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true
                };
                using (Process p = Process.Start(info))
                {
                    if (p == null) return null;
                    string output = p.StandardOutput.ReadToEnd().Trim();
                    if (!p.WaitForExit(5000) || p.ExitCode != 0) return null;
                    return output.Length == 0 ? null : output;
                }
            }
            catch (Exception)
            {
                return null;
            }
        }
    }

    /// <summary>
    /// Stamps every standalone player, whichever build entry point made it (BuildCommands,
    /// WindowsPlaytestBuilder, File → Build), with the version it was built as.
    /// </summary>
    public sealed class BuildInfoPostprocess : IPostprocessBuildWithReport
    {
        public int callbackOrder => 100;

        public void OnPostprocessBuild(BuildReport report)
        {
            ReleaseStamp.WriteBuildInfo(report.summary.platform, report.summary.outputPath);
        }
    }
}
